const translations: Record<Exclude<Language, "th">, Record<string, string>> = { en, ko };

export function getStoredLanguage(): Language {
  if (typeof window === "undefined") return "th";
  const stored = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
  return stored === "en" || stored === "ko" || stored === "th" ? stored : "th";
}

export function translate(language: Language, source: string, values: Record<string, string | number> = {}): string {
  const template = language === "th" ? source : translations[language][source] ?? source;
  return Object.entries(values).reduce((result, [key, value]) => result.replaceAll(`{${key}}`, String(value)), template);
}

export function translateCurrent(source: string, values?: Record<string, string | number>): string {
  return translate(getStoredLanguage(), source, values);
}

